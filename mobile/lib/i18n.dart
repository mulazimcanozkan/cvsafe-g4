// Language and theme preferences, plus the English -> Turkish dictionary.
//
// Every visible text goes through [tx]. The English text in the code is the
// key; in Turkish mode it is looked up here. Keys may contain `{}`
// placeholders (numbers, names...); the Turkish value refers to them as {0}, {1}.
import 'dart:ui' show PlatformDispatcher;

import 'package:flutter/foundation.dart';
import 'package:shared_preferences/shared_preferences.dart';

/// User interface preferences: dark/light theme and language (en/tr). Saved on the device.
class UiPrefs extends ChangeNotifier {
  UiPrefs._();
  static final UiPrefs instance = UiPrefs._();

  static const _darkKey = 'ui_dark';
  static const _langKey = 'ui_lang';

  bool dark = true;
  String lang = 'en';
  bool get isTurkish => lang == 'tr';

  /// Called once before the app starts. First run follows the device language.
  Future<void> load() async {
    try {
      lang = PlatformDispatcher.instance.locale.languageCode == 'tr' ? 'tr' : 'en';
    } catch (_) {}
    try {
      final p = await SharedPreferences.getInstance();
      dark = p.getBool(_darkKey) ?? dark;
      lang = p.getString(_langKey) ?? lang;
    } catch (_) {}
  }

  Future<void> setDark(bool value) async {
    dark = value;
    notifyListeners();
    try {
      final p = await SharedPreferences.getInstance();
      await p.setBool(_darkKey, value);
    } catch (_) {}
  }

  Future<void> setLang(String value) async {
    lang = value == 'tr' ? 'tr' : 'en';
    notifyListeners();
    try {
      final p = await SharedPreferences.getInstance();
      await p.setString(_langKey, lang);
    } catch (_) {}
  }

  void toggleDark() => setDark(!dark);
  void toggleLang() => setLang(isTurkish ? 'en' : 'tr');
}

/// Translates a visible text into the current language (English texts are returned as they are).
String tx(String s) {
  if (!UiPrefs.instance.isTurkish || s.isEmpty) return s;
  return _translate(s, 0);
}

/// Same as [tx] for optional texts.
String? txn(String? s) => s == null ? null : tx(s);

String _translate(String s, int depth) {
  if (s.isEmpty) return s;
  final exact = _exact[s];
  if (exact != null) return exact;
  if (depth < 3) {
    for (final p in _patterns) {
      final m = p.re.firstMatch(s);
      if (m == null) continue;
      var out = p.value;
      for (var i = 0; i < m.groupCount; i++) {
        out = out.replaceAll('{$i}', _translate(m.group(i + 1) ?? '', depth + 1));
      }
      return out;
    }
  }
  var out = s;
  for (final ph in _phrases) {
    if (out.contains(ph[0])) out = out.replaceAll(ph[0], ph[1]);
  }
  return out;
}

class _Pattern {
  _Pattern(this.re, this.value, this.weight);
  final RegExp re;
  final String value;
  final int weight;
}

final Map<String, String> _exact = {
  for (final e in _tr.entries)
    if (!e.key.contains('{}')) e.key: e.value,
};

// Patterns with more fixed text are tried first so the most specific one wins.
final List<_Pattern> _patterns = () {
  final list = <_Pattern>[
    for (final e in _tr.entries)
      if (e.key.contains('{}'))
        _Pattern(
          RegExp('^${e.key.split('{}').map(RegExp.escape).join('(.*?)')}\$', dotAll: true),
          e.value,
          e.key.replaceAll('{}', '').length,
        ),
  ];
  list.sort((a, b) => b.weight.compareTo(a.weight));
  return list;
}();

